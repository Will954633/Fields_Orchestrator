if __name__ == "__main__":
    load_env()

    if len(sys.argv) < 2:
        print("Usage: python3 scripts/google_indexing.py <command>")
        print("Commands: auth, submit-all, submit <url>, submit-new, status")
        print("  submit-new [--since ISO8601] [--no-advance]   # --since backfills an "
              "older window; pair with --no-advance so it does not move the live watermark")
        sys.exit(1)

    command = sys.argv[1]
    since_arg = None
    if "--since" in sys.argv:
        since_arg = sys.argv[sys.argv.index("--since") + 1]
    no_advance = "--no-advance" in sys.argv

    if command == "auth":
        cmd_auth()
    elif command == "submit-all":
        cmd_submit_all()
    elif command == "submit":
        if len(sys.argv) < 3:
            print("Usage: python3 scripts/google_indexing.py submit <url>")
            sys.exit(1)
        cmd_submit(sys.argv[2])
    elif command == "submit-new":
        # Rule 7: this is the nightly cron path and had NO heartbeat, which is the only
        # reason 9 straight nights of zero submissions went unnoticed. job_run records
        # error + traceback on the raise added in cmd_submit_new and re-raises.
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
        from job_status import job_run
        with job_run("google_indexing_submit_new", cadence_hours=24,
                     title="Google Indexing API — new/changed URLs") as beat:
            beat.detail = "submit-new"
            cmd_submit_new(since=since_arg, advance_watermark=not no_advance)
    elif command == "status":
        cmd_status()
    else:
        print(f"Unknown command: {command}")
        sys.exit(1)
